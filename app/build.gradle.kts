// app/build.gradle.kts — módulo do aplicativo (épico 8.0).
// App phone-only, retrato apenas, offline (spec.md §2/§3). minSdk 26 (mesmo piso do I See Life
// Android — cobre BroadcastReceiver de BOOT_COMPLETED e AlarmManager exato sem ressalvas).
// Compose + Room. Sem CameraX, sem Play Billing (não há câmera nem compra neste app).

import java.io.FileInputStream
import java.util.Properties

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.ksp)
}

// Assinatura de release (épico de publicação). Lê o keystore.properties da raiz (NÃO versionado);
// se não existir, o build de release sai sem assinatura (útil em dev). Formato do arquivo:
//   storeFile=/caminho/horadoremedio-upload.jks
//   storePassword=...
//   keyAlias=horadoremedio
//   keyPassword=...
val keystorePropsFile = rootProject.file("keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) FileInputStream(keystorePropsFile).use { load(it) }
}

android {
    namespace = "com.dablab.horadoremedio"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.dablab.horadoremedio"   // mesmo namespace de marca do iOS (spec.md §1)
        minSdk = 26
        targetSdk = 35
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables { useSupportLibrary = true }
    }

    signingConfigs {
        if (keystorePropsFile.exists()) {
            create("release") {
                storeFile = file(keystoreProps["storeFile"] as String)
                storePassword = keystoreProps["storePassword"] as String
                keyAlias = keystoreProps["keyAlias"] as String
                keyPassword = keystoreProps["keyPassword"] as String
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"       // permite debug e release lado a lado
            isMinifyEnabled = false
        }
        release {
            isMinifyEnabled = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (keystorePropsFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }

    buildFeatures {
        compose = true
    }

    packaging {
        resources { excludes += "/META-INF/{AL2.0,LGPL2.1}" }
    }
}

